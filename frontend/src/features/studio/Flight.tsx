"use client";

import "maplibre-gl/dist/maplibre-gl.css";

import type { GeoJSONSource, Map as MapLibreMap } from "maplibre-gl";
import { useEffect, useRef, useState, useSyncExternalStore } from "react";

import { Icon } from "@/components/ui/Icon";
import type { Dictionary } from "@/i18n";
import type { Locale } from "@/i18n/config";
import {
  type Cam,
  cameraAt,
  constructionAt,
  type Preset,
  plotRing,
  presetPath,
  type Stage,
} from "@/lib/map/flight";
import type { MapConfig } from "@/lib/map/provider";
import { extrusionColor, styleFor } from "@/lib/map/style";
import { maplibreWorkerUrl } from "@/lib/map/worker";

type Mode = Preset | "custom" | "construction";

function isDark(): boolean {
  const forced = document.documentElement.dataset.theme;
  if (forced) return forced === "dark";
  return window.matchMedia("(prefers-color-scheme: dark)").matches;
}

const noSubscribe = () => () => undefined;

function pickMime(): string | null {
  if (typeof MediaRecorder === "undefined") return null;
  for (const type of ["video/mp4;codecs=avc1", "video/webm;codecs=vp9", "video/webm"]) {
    if (MediaRecorder.isTypeSupported(type)) return type;
  }
  return null;
}

/**
 * Drone flight and construction sequence over the real map. The camera is a
 * MapLibre camera over OpenStreetMap geometry (buildings extruded to their
 * mapped heights); recording captures the map canvas in the browser. Nothing
 * here is generated by an AI model, and the page says so.
 */
export function Flight({
  config,
  dict,
  locale,
  lon,
  lat,
  floors,
  areaM2,
}: {
  config: MapConfig;
  dict: Dictionary;
  locale: Locale;
  lon: number;
  lat: number;
  floors: number;
  areaM2: number;
}) {
  const f = dict.flight;
  const container = useRef<HTMLDivElement>(null);
  const mapRef = useRef<MapLibreMap | null>(null);
  const frame = useRef<number | null>(null);
  const recorder = useRef<MediaRecorder | null>(null);
  const [ready, setReady] = useState(false);
  const [mode, setMode] = useState<Mode>("approach");
  const [altitude, setAltitude] = useState(0);
  const [seconds, setSeconds] = useState(12);
  const [playing, setPlaying] = useState(false);
  const [recording, setRecording] = useState(false);
  const [video, setVideo] = useState<{ url: string; seconds: number; ext: string } | null>(null);
  const [waypoints, setWaypoints] = useState<Cam[]>([]);
  const [stage, setStage] = useState<Stage | null>(null);
  // Known only in the browser; the server renders "can record" and the client
  // corrects it after hydration (no mismatch).
  const canRecord = useSyncExternalStore(
    noSubscribe,
    () => pickMime() !== null,
    () => true,
  );
  const finalHeight = Math.max(3, floors * 3.2);

  useEffect(() => {
    let cancelled = false;
    let map: MapLibreMap | null = null;
    (async () => {
      const maplibre = await import("maplibre-gl");
      if (cancelled || !container.current) return;
      maplibre.setWorkerUrl(maplibreWorkerUrl(maplibre.getVersion()));
      const dark = isDark();
      map = new maplibre.Map({
        container: container.current,
        style: styleFor(config, dark, locale) as never,
        center: [lon, lat],
        zoom: 16.4,
        pitch: 55,
        bearing: -20,
        maxPitch: 75,
        attributionControl: { compact: true },
        // Recording reads the canvas between frames.
        canvasContextAttributes: { preserveDrawingBuffer: true },
      });
      mapRef.current = map;
      map.addControl(new maplibre.NavigationControl({ visualizePitch: true }), "top-right");
      const m = map;
      m.on("style.load", () => {
        const vector = Object.entries(m.getStyle().sources).find(
          ([, s]) => s.type === "vector",
        )?.[0];
        const firstSymbol = m.getStyle().layers.find((l) => l.type === "symbol")?.id;
        if (vector) {
          m.addLayer(
            {
              id: "flight-3d",
              type: "fill-extrusion",
              source: vector,
              "source-layer": "building",
              minzoom: 13,
              paint: {
                "fill-extrusion-color": extrusionColor(dark),
                "fill-extrusion-height": ["coalesce", ["get", "render_height"], 6],
                "fill-extrusion-base": ["coalesce", ["get", "render_min_height"], 0],
                "fill-extrusion-opacity": 0.9,
                "fill-extrusion-vertical-gradient": true,
              },
            },
            firstSymbol,
          );
        }
        const ring = plotRing(lon, lat, areaM2);
        m.addSource("plot", {
          type: "geojson",
          data: {
            type: "Feature",
            properties: {},
            geometry: { type: "Polygon", coordinates: [ring] },
          },
        });
        m.addLayer({
          id: "plot-line",
          type: "line",
          source: "plot",
          paint: { "line-color": "#22d3ee", "line-width": 2, "line-dasharray": [2, 1.5] },
        });
        m.addLayer({
          id: "mass",
          type: "fill-extrusion",
          source: "plot",
          paint: {
            "fill-extrusion-color": dark ? "#e9e2d4" : "#c9bfae",
            "fill-extrusion-height": 0,
            "fill-extrusion-base": 0,
            "fill-extrusion-opacity": 0,
          },
        });
        m.addSource("target", {
          type: "geojson",
          data: {
            type: "Feature",
            properties: {},
            geometry: { type: "Point", coordinates: [lon, lat] },
          },
        });
        m.addLayer({
          id: "target",
          type: "circle",
          source: "target",
          paint: {
            "circle-radius": 6,
            "circle-color": "#10b981",
            "circle-stroke-color": "#ffffff",
            "circle-stroke-width": 2,
            "circle-pitch-alignment": "map",
          },
        });
        setReady(true);
      });
    })().catch(() => undefined);
    return () => {
      cancelled = true;
      if (frame.current) cancelAnimationFrame(frame.current);
      map?.remove();
      mapRef.current = null;
    };
  }, [config, locale, lon, lat, areaM2]);

  function setMass(height: number, opacity: number) {
    const map = mapRef.current;
    if (!map?.getLayer("mass")) return;
    map.setPaintProperty("mass", "fill-extrusion-height", height);
    map.setPaintProperty("mass", "fill-extrusion-opacity", opacity);
  }

  function pathFor(m: Mode): Cam[] {
    if (m === "custom") return waypoints;
    if (m === "construction") return presetPath("orbit", lon, lat, altitude - 0.4);
    return presetPath(m, lon, lat, altitude);
  }

  function stop() {
    if (frame.current) cancelAnimationFrame(frame.current);
    frame.current = null;
    setPlaying(false);
    if (recorder.current?.state === "recording") recorder.current.stop();
  }

  /** Plays the current path once; resolves when it ends (or is stopped). */
  function play(onEnd?: () => void, forRecording = false) {
    const map = mapRef.current;
    const path = pathFor(mode);
    if (!map || path.length < 2) return;
    stop();
    const construction = mode === "construction";
    const linear = mode === "orbit" || construction;
    const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    const duration = seconds * 1000;
    if (reduce && !forRecording) {
      // No movement: show where the path ends (and the finished massing).
      const end = cameraAt(path, 1, linear);
      map.jumpTo({
        center: [end.lon, end.lat],
        zoom: end.zoom,
        pitch: end.pitch,
        bearing: end.bearing,
      });
      if (construction) {
        const s = constructionAt(1, finalHeight);
        setMass(s.height, s.solid);
        setStage(s.stage);
      }
      onEnd?.();
      return;
    }
    setPlaying(true);
    const t0 = performance.now();
    const tick = (now: number) => {
      const t = Math.min(1, (now - t0) / duration);
      const cam = cameraAt(path, t, linear);
      map.jumpTo({
        center: [cam.lon, cam.lat],
        zoom: cam.zoom,
        pitch: cam.pitch,
        bearing: cam.bearing,
      });
      if (construction) {
        const s = constructionAt(t, finalHeight);
        setMass(s.height, s.solid);
        setStage((prev) => (prev === s.stage ? prev : s.stage));
      }
      if (t < 1) frame.current = requestAnimationFrame(tick);
      else {
        frame.current = null;
        setPlaying(false);
        onEnd?.();
      }
    };
    frame.current = requestAnimationFrame(tick);
  }

  function record() {
    const map = mapRef.current;
    const mime = pickMime();
    if (!map || !mime) return;
    const canvas = map.getCanvas() as HTMLCanvasElement & {
      captureStream?: (fps: number) => MediaStream;
    };
    if (!canvas.captureStream) return;
    const stream = canvas.captureStream(30);
    const chunks: Blob[] = [];
    const rec = new MediaRecorder(stream, { mimeType: mime, videoBitsPerSecond: 6_000_000 });
    recorder.current = rec;
    rec.ondataavailable = (e) => e.data.size && chunks.push(e.data);
    rec.onstop = () => {
      setRecording(false);
      stream.getTracks().forEach((track) => track.stop());
      const blob = new Blob(chunks, { type: mime.split(";")[0] });
      setVideo((old) => {
        if (old) URL.revokeObjectURL(old.url);
        return {
          url: URL.createObjectURL(blob),
          seconds,
          ext: mime.includes("mp4") ? "mp4" : "webm",
        };
      });
    };
    setRecording(true);
    rec.start(250);
    play(() => setTimeout(() => rec.state === "recording" && rec.stop(), 150), true);
  }

  function addWaypoint() {
    const map = mapRef.current;
    if (!map) return;
    const c = map.getCenter();
    setWaypoints((list) => [
      ...list,
      {
        lon: c.lng,
        lat: c.lat,
        zoom: map.getZoom(),
        pitch: map.getPitch(),
        bearing: map.getBearing(),
      },
    ]);
  }

  const modes: [Mode, string][] = [
    ["approach", f.approach],
    ["orbit", f.orbit],
    ["reveal", f.reveal],
    ["custom", f.custom],
    ["construction", f.construction],
  ];
  const canPlay = ready && pathFor(mode).length >= 2;

  return (
    <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_340px]">
      <div className="relative overflow-hidden rounded-[var(--radius-card)] bg-fill shadow-[inset_0_0_0_1px_var(--hairline)]">
        <div ref={container} className="aspect-[16/10] w-full" data-testid="flight-map" />
        {mode === "construction" && stage && (
          <p className="surface-float absolute start-4 top-4 rounded-[var(--radius-control)] px-3 py-1.5 text-sm font-medium text-ink">
            {f.stages[stage]}
          </p>
        )}
        {recording && (
          <p className="absolute end-14 top-4 flex items-center gap-2 rounded-[var(--radius-control)] bg-danger px-3 py-1.5 text-sm font-medium text-white">
            <span className="size-2 animate-pulse rounded-full bg-white" />
            {f.recording}
          </p>
        )}
      </div>

      <div className="flex flex-col gap-6">
        <fieldset className="flex flex-col gap-2">
          <legend className="label mb-2">{f.presets}</legend>
          <div className="flex flex-wrap gap-2">
            {modes.map(([m, label]) => (
              <button
                key={m}
                type="button"
                aria-pressed={mode === m}
                onClick={() => {
                  stop();
                  setMode(m);
                  if (m !== "construction") {
                    setMass(0, 0);
                    setStage(null);
                  }
                }}
                className="chip"
              >
                {label}
              </button>
            ))}
          </div>
        </fieldset>

        {mode === "custom" && (
          <div className="flex flex-col gap-2 rounded-[var(--radius-control)] bg-fill/60 p-4">
            <p className="text-sm text-ink-2">{f.waypointsHint}</p>
            <div className="flex flex-wrap items-center gap-2">
              <button type="button" onClick={addWaypoint} className="btn btn-secondary btn-sm">
                <Icon name="plus" className="size-4" />
                {f.addWaypoint}
              </button>
              {waypoints.length > 0 && (
                <button
                  type="button"
                  onClick={() => setWaypoints([])}
                  className="btn btn-quiet btn-sm"
                >
                  {f.clearWaypoints}
                </button>
              )}
              <span className="caption tabular">
                {f.waypoints.replace("{n}", String(waypoints.length))}
              </span>
            </div>
          </div>
        )}

        {mode !== "custom" && (
          <label className="flex flex-col gap-2">
            <span className="label">{f.altitude}</span>
            <input
              type="range"
              min={-1}
              max={1.5}
              step={0.1}
              value={altitude}
              onChange={(e) => setAltitude(Number(e.target.value))}
            />
          </label>
        )}
        <label className="flex flex-col gap-2">
          <span className="label flex justify-between">
            {f.speed}
            <span className="tabular normal-case">{f.seconds.replace("{n}", String(seconds))}</span>
          </span>
          <input
            type="range"
            min={6}
            max={24}
            step={1}
            value={seconds}
            onChange={(e) => setSeconds(Number(e.target.value))}
          />
        </label>

        <div className="flex flex-wrap gap-2">
          {playing ? (
            <button type="button" onClick={stop} className="btn btn-secondary">
              {f.stop}
            </button>
          ) : (
            <button
              type="button"
              onClick={() => play()}
              disabled={!canPlay || recording}
              className="btn btn-secondary"
            >
              <Icon name="play" className="size-4" />
              {f.play}
            </button>
          )}
          <button
            type="button"
            onClick={record}
            disabled={!canPlay || !canRecord || recording || playing}
            className="btn btn-primary"
          >
            <Icon name="video" className="size-4" />
            {recording ? f.recording : f.record}
          </button>
        </div>
        {!canRecord && <p className="caption">{f.noRecorder}</p>}

        {video && (
          <div className="flex flex-col gap-2" data-testid="flight-video">
            <video src={video.url} controls className="w-full rounded-[var(--radius-control)]" />
            <p className="caption">{f.recorded.replace("{n}", String(video.seconds))}</p>
            <a
              href={video.url}
              download={`makan-flight.${video.ext}`}
              className="btn btn-secondary btn-sm w-fit"
            >
              {f.download}
            </a>
          </div>
        )}

        <p className="rounded-[var(--radius-control)] bg-gold-100 p-4 text-sm leading-relaxed text-ink-2 shadow-[inset_0_0_0_1px_var(--gold-line)]">
          {mode === "construction" ? f.constructionHonesty : f.honesty}
        </p>
      </div>
    </div>
  );
}
